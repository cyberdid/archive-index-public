def test_projects_inside_site_or_build_folders_keep_their_html(tmp_path):
    from archive_index.sources import discover_html

    root = tmp_path / "site" / "Projects"  # the scanned root itself sits under a folder named "site"
    (root / "wiki").mkdir(parents=True)
    (root / "wiki" / "plan.html").write_text("<html><body>план</body></html>", encoding="utf-8")
    names = [p.name for p in discover_html(root)]
    assert names == ["plan.html"]


def test_mirror_and_wine_runtime_files_are_skipped_for_text_and_images(tmp_path):
    from archive_index.sources import discover_images, discover_text

    root = tmp_path / "Projects"
    own = root / "notes"
    mirror = root / "Nvidia" / "crawl" / "files.ettus.com"
    wine = root / "projdelta" / "wineprefix-webview2" / "drive_c"
    for d in (own, mirror, wine):
        d.mkdir(parents=True)
    (own / "a.txt").write_text("мій конспект", encoding="utf-8")
    (mirror / "b.txt").write_text("чужа документація", encoding="utf-8")
    (wine / "c.txt").write_text("кеш браузера", encoding="utf-8")
    (own / "pic.png").write_bytes(b"\x89PNG")
    (mirror / "logo.png").write_bytes(b"\x89PNG")
    assert [p.name for p in discover_text(root)] == ["a.txt"]
    assert [p.name for p in discover_images(root)] == ["pic.png"]
