import json
import shutil

import numpy as np
import pytest

from archive_index.indexer import run_index
from archive_index.search import VectorCache, hybrid
from archive_index.sources import parse_config, parse_html, parse_notebook, parse_text
from archive_index.store import Store


class FakeEmbedder:
    def documents(self, texts, titles=None):
        return np.ones((len(texts), 4), dtype=np.float32) if texts else np.zeros((0, 0), np.float32)

    def query(self, text):
        return np.ones(4, dtype=np.float32)


def test_html_drops_scripts_and_keeps_headings(tmp_path):
    f = tmp_path / "page.html"
    f.write_text("<html><title>Звіт</title><script>var secret=1;</script>"
                 "<h2>Вступ</h2><p>Антена працює.</p><style>p{}</style>", encoding="utf-8")
    doc = parse_html(f, tmp_path)
    text = " ".join(u.text for u in doc.units)
    assert "Антена працює" in text
    assert "secret" not in text and "p{}" not in text
    assert any(u.heading == "Вступ" for u in doc.units)


def test_notebook_keeps_cells_without_outputs(tmp_path):
    f = tmp_path / "nb.ipynb"
    nb = {"cells": [
        {"cell_type": "markdown", "source": ["# Аналіз\n"], "outputs": []},
        {"cell_type": "code", "source": ["print(42)"], "outputs": [{"text": ["OUTPUTMARK"]}]},
    ]}
    f.write_text(json.dumps(nb), encoding="utf-8")
    doc = parse_notebook(f, tmp_path)
    text = " ".join(u.text for u in doc.units)
    assert "Аналіз" in text and "print(42)" in text
    assert "OUTPUTMARK" not in text


def test_plain_text_and_config_are_parsed_as_their_collection(tmp_path):
    t = tmp_path / "нотатка.txt"
    t.write_text("Перевірити плату RVZ0014A", encoding="utf-8")
    assert parse_text(t, tmp_path).collection == "docs"
    c = tmp_path / "compose.yaml"
    c.write_text("image: nginx", encoding="utf-8")
    assert parse_config(c, tmp_path).collection == "config"


def test_config_and_logs_are_opt_in(tmp_path):
    projects = tmp_path / "Projects" / "p"
    projects.mkdir(parents=True)
    (projects / "settings.yaml").write_text("zetaopt: 1", encoding="utf-8")
    store = Store(tmp_path / "o.sqlite3")
    run_index(store, FakeEmbedder(), projects_root=tmp_path / "Projects", home=tmp_path / "h",
              collections=("wiki", "docs"))
    assert "config" not in store.stats()
    run_index(store, FakeEmbedder(), projects_root=tmp_path / "Projects", home=tmp_path / "h",
              collections=("config",))
    assert store.stats()["config"]["documents"] == 1
    store.close()


@pytest.mark.skipif(shutil.which("soffice") is None, reason="LibreOffice not installed")
def test_legacy_rtf_is_converted_and_indexed(tmp_path):
    projects = tmp_path / "Projects" / "p"
    projects.mkdir(parents=True)
    rtf = projects / "old.rtf"
    rtf.write_text(r"{\rtf1\ansi Old document about the antenna-relay station.\par}", encoding="utf-8")
    store = Store(tmp_path / "rtf.sqlite3")
    report = run_index(store, FakeEmbedder(), projects_root=tmp_path / "Projects",
                       home=tmp_path / "h", collections=("docs",))
    assert report.errors == []
    hits = hybrid(store, VectorCache(store), "relay", None, mode="lexical", k=3)
    assert hits and hits[0].path.endswith("old.rtf")
    store.close()


def test_epub_chapters_are_indexed(tmp_path):
    import zipfile

    from archive_index.sources import parse_epub

    f = tmp_path / "book.epub"
    with zipfile.ZipFile(f, "w") as z:
        z.writestr("chapter1.xhtml", "<html><body><h1>Розділ</h1><p>Антена ретранслятора.</p></body></html>")
        z.writestr("style.css", "p{}")
    doc = parse_epub(f, tmp_path)
    text = " ".join(u.text for u in doc.units)
    assert "Антена ретранслятора" in text and "p{}" not in text
    assert doc.units[0].locator.startswith("chapter1.xhtml")


def test_third_party_html_is_not_indexed(tmp_path):
    from archive_index.sources import is_third_party_html

    assert is_third_party_html(tmp_path / "x" / "crawl" / "files.ettus.com" / "manual.html")
    assert is_third_party_html(tmp_path / "proj" / "htmlcov" / "index.html")
    assert is_third_party_html(tmp_path / "proj" / "wineprefix" / "a.html")
    own = tmp_path / "notes" / "page.html"
    own.parent.mkdir(parents=True)
    own.write_text("<html><body>мій конспект</body></html>", encoding="utf-8")
    assert not is_third_party_html(own)
    gen = tmp_path / "api" / "index.html"
    gen.parent.mkdir(parents=True)
    gen.write_text("<html><!-- Generated by Doxygen 1.9 --><body>API</body></html>", encoding="utf-8")
    assert is_third_party_html(gen)


def test_machine_output_text_is_skipped_and_prose_kept(tmp_path):
    from archive_index.sources import discover_text, is_machine_text

    dump = "\n".join(f"{i} {i * 3} {i * 7} 1024 0x{i:04x}" for i in range(60))
    assert is_machine_text(dump)
    assert is_machine_text("abc\x00def")
    assert not is_machine_text("Антена працює на частоті 1800 МГц.\nЗвіт за тиждень.")
    (tmp_path / "dump.txt").write_text(dump, encoding="utf-8")
    (tmp_path / "note.txt").write_text("Нотатка про ретранслятор.", encoding="utf-8")
    names = sorted(p.name for p in discover_text(tmp_path))
    assert names == ["note.txt"]


